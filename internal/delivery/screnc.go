// encodeTable[c][pick] = encoded byte e such that decodeDict[e][pick] == c.
// encodeSet marks valid entries (0 is a valid encoded byte for c=0, so we need
// a separate presence flag).
var encodeTable [128][3]byte
var encodeSet [128][3]bool

// escapes: plaintext byte -> "@"+repr. \r \n < > @ are escaped; everything else
// goes through encodeTable.
var screncEscapes = map[byte]byte{
	0x0d: '#',
	0x0a: '&',
	0x3c: '!', // '<'
	0x3e: '*', // '>'
	0x40: '$', // '@'
}

func init() {
	for e := 0; e < 128; e++ {
		for p := 0; p < 3; p++ {
			c := decodeDict[e][p]
			// first-wins; any e with decodeDict[e][p]==c decodes back to c.
			if !encodeSet[c][p] {
				encodeTable[c][p] = byte(e)
				encodeSet[c][p] = true
			}
		}
	}
}

// screncEncodeBody returns the encoded body bytes for the given plaintext.
// j (output position) increments for every plaintext char including escaped
// ones, matching the decoder's bookkeeping.
func screncEncodeBody(plain []byte) ([]byte, error) {
	var out []byte
	j := 0
	for _, c := range plain {
		if r, ok := screncEscapes[c]; ok {
			out = append(out, '@', r)
			j++
			continue
		}
		if c >= 128 {
			return nil, fmt.Errorf("screnc: non-ASCII byte 0x%02x not encodable (JScript body must be ASCII)", c)
		}
		pick := pickEncoding[j%64]
		if !encodeSet[c][pick] {
			return nil, fmt.Errorf("screnc: byte 0x%02x has no encoding for pick %d", c, pick)
		}
		out = append(out, encodeTable[c][pick])
		j++
	}
	return out, nil
}

// screncDecodeBody is the inverse of screncEncodeBody, used by the round-trip
// test. It mirrors the ReactOS decoder's per-char logic.
func screncDecodeBody(enc []byte) ([]byte, error) {
	var out []byte
	j := 0
	i := 0
	for i < len(enc) {
		if enc[i] == '@' {
			if i+1 >= len(enc) {
				return nil, fmt.Errorf("screnc: trailing @")
			}
			r := enc[i+1]
			var c byte
			switch r {
			case '#':
				c = 0x0d
			case '&':
				c = 0x0a
			case '!':
				c = 0x3c
			case '*':
				c = 0x3e
			case '$':
				c = 0x40
			default:
				return nil, fmt.Errorf("screnc: bad escape @%c", r)
			}
			out = append(out, c)
			j++
			i += 2
			continue
		}
		e := enc[i]
		if e >= 128 {
			return nil, fmt.Errorf("screnc: encoded byte >= 128")
		}
		pick := pickEncoding[j%64]
		out = append(out, decodeDict[e][pick])
		j++
		i++
	}
	return out, nil
}

// screncChecksum returns the running sum of decoded plaintext byte values.
func screncChecksum(plain []byte) uint32 {
	var s uint32
	for _, c := range plain {
		s += uint32(c)
	}
	return s
}

// b64LE encodes a uint32 as little-endian bytes then standard base64 (-> 6
// chars + "==", 8 chars total), the format scrdec.py decodes for the length and
// checksum fields.
func b64LE(n uint32) string {
	var b [4]byte
	binary.LittleEndian.PutUint32(b[:], n)
	return base64.StdEncoding.EncodeToString(b[:]) // 4 bytes -> 8 chars, ends with "=="
}

// ScrencEncode produces a full .jse/.vbe file body for the given plaintext.
func ScrencEncode(plain []byte) (string, error) {
	body, err := screncEncodeBody(plain)
	if err != nil {
		return "", err
	}
	var sb strings.Builder
	sb.WriteString("#@~^")
	sb.WriteString(b64LE(uint32(len(body)))) // length of encoded body
	sb.WriteString(string(body))
	sb.WriteString(b64LE(screncChecksum(plain))) // checksum of plaintext bytes
	sb.WriteString("^#~@")
	return sb.String(), nil
}